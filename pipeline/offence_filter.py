"""§2 media offence-language pre-filter — HIGH RECALL, tuned for media sources (tier 2/3).

Court sources (tier 1: Indian Kanoon, hc_judgments) keep the STATUTE pre-filter — a judgment
always cites its sections, and that filter gates per-document billing. MEDIA is different:
newspapers report the OFFENCE, not the statute ("man held for raping a minor" cites nothing),
and they do so in many languages. A section-anchored, English-only filter therefore scores
every regional crime feed at zero by construction — the defect this fixes (issue: Phase 8 §2).

This filter is offence-LANGUAGE and HIGH RECALL / low precision. Its ONLY job is to skip a
document that is OBVIOUSLY irrelevant, so we do not pay an LLM to read it. Gemini's ``in_scope``
boolean makes the actual scope decision. Missing a true case is the operator's red line, so we
optimise for recall and accept false positives — a false positive costs one cheap LLM call,
which the scope gate then rejects.

Matching:
- ROMAN/English terms are WORD-BOUNDARIED (so "rape" does not fire inside "grape"/"draped" and
  "minor" not inside ordinary "minor injury" — those boundaries matter because English feeds
  run through the same filter).
- NATIVE-SCRIPT terms are matched as SUBSTRINGS (the scripts are distinctive; a Devanagari/
  Telugu/Tamil offence word in a document is signal). A few native substrings deliberately
  over-match (e.g. Devanagari रेप is inside रेपो / "repo rate") — kept, per the recall rule.

The term sets were built + adversarially reviewed by native-language sub-editors (one agent per
enabled language). A language whose set does not exist yet MUST keep its feed disabled — never
enabled to produce silent zeros (Phase 8 §4).
"""

