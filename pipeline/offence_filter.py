_ALL_NATIVE: frozenset[str] = frozenset().union(*NATIVE_OFFENCE_TERMS.values())

# One case-insensitive, word-boundaried alternation over the roman terms (longest first, so a
# multi-word term wins over its prefix). ASCII boundaries only, so it never splits native script.
_ROMAN_RE = re.compile(
    r"(?<![a-z])(?:"
    + "|".join(re.escape(t) for t in sorted(ROMAN_OFFENCE_TERMS, key=len, reverse=True))
    + r")(?![a-z])",
    re.IGNORECASE,
)


def media_offence_hit(text: str) -> bool:
    """True if ``text`` plausibly reports a sexual offence (any covered language). HIGH RECALL —
    a hit means "send to the LLM", not "this is in scope". Empty/non-str is never a hit."""
    if not isinstance(text, str) or not text:
        return False
    if _ROMAN_RE.search(text):
        return True
    if any(term in text for term in _ALL_NATIVE):
        return True
    # Retain the statute patterns as additional hits (a media report may cite a section).
    return statute_qualifies(text)


def offence_term_languages(text: str) -> list[str]:
    """Which covered languages' native offence terms appear in ``text`` (for accounting)."""
    if not isinstance(text, str) or not text:
        return []
    return [lang for lang, terms in NATIVE_OFFENCE_TERMS.items() if any(t in text for t in terms)]
